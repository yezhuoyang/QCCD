"""The full-stack machine: a gadget town that can run a FormalRV program.

A program written in Pauli-product measurements (FormalRV's `.qppm`, lowered to `.qec`) needs
places the Shor town does not have: Pauli-product benches (`ppm_d3`: any product of one X̄ or
Z̄ from up to three blocks) and pharmacies that make |Ȳ⟩ blocks (`prep q Y`, the resource a π/4
rotation consumes).  It also keeps more blocks alive at once, so it has memories, which correct
a resting block in place.

    python -m qccd.fullstack machine     writes examples/gadgets/floorplans/fullstack.floor

The floorplan is generated by the town's own layout (`qccd.gadget.town`: rows of places between
streets, every door on a road) and written as `.floor` text, so it is read, judged (F1-F9) and
edited like every other floorplan; a program names it with `floorplan "fullstack"`.
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FLOORPLAN = REPO / "examples" / "gadgets" / "floorplans" / "fullstack.floor"

#: (instance, master), row by row
ROWS = [
    [("depot1", "depot9"), ("prep", "prep_d3"), ("clinic", "se_d3"), ("bench1", "ppm_d3"),
     ("post1", "read_d3"), ("mem1", "mem_d3")],
    [("pharmacy1", "inj_d3"), ("mem2", "mem_d3"), ("bench2", "ppm_d3"), ("mem3", "mem_d3"),
     ("post2", "read_d3")],
    [("pharmacy2", "inj_d3"), ("mem4", "mem_d3"), ("mem5", "mem_d3"), ("depot2", "depot9")],
]

COMMENT = """\
The full-stack machine: a gadget town that runs a FormalRV program (qccd/fullstack/machine.py).
Generated by the town's own layout -- rows of places between streets, every door on a road --
and judged by the floorplan rules F1-F9 like any other.

  compute  two Pauli-product benches (ppm_d3): every PPM of the program, any product of one
           X-bar or Z-bar from up to three blocks; a preparation place, a syndrome clinic and
           two readouts
  factory  two pharmacies (inj_d3): the |Y> blocks a pi/4 rotation consumes
  memory   five memories: a block waiting between measurements rests corrected
  supply   two depots
  control  the decoder and the classical memory, wired to every door that carries bits"""


def library(leaves):
    from ..gadget.town import town
    return town(leaves, name="fullstack_d3", rows=ROWS)


def write_floorplan(leaves, path: Path = FLOORPLAN) -> Path:
    from ..gadget.floorplan import write
    lib = library(leaves)
    text = write(lib, title="A machine for FormalRV programs (surface code, d = 3)", comment=COMMENT)
    Path(path).write_text(text, encoding="utf-8")
    return Path(path)
