"""The full-stack machine: a gadget town that can run a FormalRV program.

A program written in Pauli-product measurements (FormalRV's `.qppm`, lowered to `.qec`) needs
places the Shor town does not have: Pauli-product benches (`ppm_d3`: any product of one X̄ or
Z̄ from up to four blocks) and pharmacies that make |Ȳ⟩ blocks (`prep q Y`, the resource a π/4
rotation consumes).  It also keeps more blocks alive at once, so it has memories, which correct
a resting block in place.

    python -m qccd.fullstack machine     writes examples/gadgets/floorplans/fullstack.floor

The floorplan is generated by the town's own layout (`qccd.gadget.town`: rows of places between
streets, every door on a road) and written as `.floor` text, so it is read, judged (F1-F9) and
edited like every other floorplan; a program names it with `floorplan "fullstack"`.
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FLOORPLAN = REPO / "examples" / "gadgets" / "floorplans" / "fullstack.floor"

#: (instance, master), row by row
ROWS = [
    [("depot1", "depot9"), ("prep", "prep_d3"), ("clinic", "se_d3"), ("bench1", "ppm_d3"),
     ("post1", "read_d3"), ("mem1", "mem_d3"), ("mem2", "mem_d3")],
    [("pharmacy1", "inj_d3"), ("factory1", "msf15"), ("mem3", "mem_d3"), ("bench2", "ppm_d3"),
     ("mem4", "mem_d3"), ("post2", "read_d3"), ("mem5", "mem_d3")],
    [("pharmacy2", "inj_d3"), ("factory2", "msf15"), ("mem6", "mem_d3"), ("mem7", "mem_d3"),
     ("mem8", "mem_d3"), ("zone1", "zone_d3"), ("depot2", "depot9")],
]

COMMENT = """\
The full-stack machine: a gadget town that runs a FormalRV program (qccd/fullstack/machine.py).
Generated by the town's own layout -- rows of places between streets, every door on a road --
and judged by the floorplan rules F1-F9 like any other.

  compute  two Pauli-product benches (ppm_d3): every PPM of the program, any product of one
           X-bar or Z-bar from up to four blocks; a preparation place, a syndrome clinic and
           two readouts
  factory  two 15-to-1 factories (msf15), each beside a pharmacy (inj_d3): the T states a
           pi/8 rotation consumes, and the |Y> blocks a pi/4 rotation consumes
  memory   eight memories and a zone: a block waiting between measurements rests corrected
  supply   two depots
  control  the decoder and the classical memory, wired to every door that carries bits"""


def wide_rows(memories: int = 32, benches: int = 4, factories: int = 4, rotations: int = 2,
              per_row: int = 9) -> list:
    """Rows for a wider machine: a program that keeps many blocks alive across its gadgets
    (each lives in a memory of its own, `qccd.gadget.fold`) needs a memory per block, and
    enough benches and factories to keep them busy; rotations finer than T need rotation
    sources (`rot1`), whose ions a pharmacy encodes.  Compute and supply first, then memories,
    `per_row` places a row."""
    # (the rotation sources first: a small bay's doors sit close, and only the first row's
    # street keeps their junctions apart -- `town` refuses the layouts that do not)
    head = [(f"lens{k}", "rot1") for k in range(1, rotations + 1)]
    head += [("depot1", "depot9"), ("prep", "prep_d3"), ("clinic", "se_d3")]
    for k in range(1, factories + 1):
        head += [(f"pharmacy{k}", "inj_d3"), (f"factory{k}", "msf15")]
    for k in range(1, benches + 1):
        head.append((f"bench{k}", "ppm_d3"))
    head += [("post1", "read_d3"), ("post2", "read_d3"), ("zone1", "zone_d3")]
    places = head + [(f"mem{k}", "mem_d3") for k in range(1, memories + 1)] + [("depot2", "depot9")]
    return [places[i:i + per_row] for i in range(0, len(places), per_row)]


WIDE_COMMENT = """\
A wider full-stack machine (qccd/fullstack/machine.py, wide_rows): the same places as the
full-stack machine, more of them -- {benches} Pauli-product benches, {factories} factories each
beside a pharmacy, {rotations} rotation sources (for rotations finer than T), {memories} memories
(one for every block a program keeps alive across its gadgets) -- in rows of {per_row} between
streets, judged by F1-F9 like any other."""


def library(leaves, rows=None, name: str = "fullstack_d3"):
    from ..gadget.town import town
    return town(leaves, name=name, rows=rows or ROWS)


def write_floorplan(leaves, path: Path = FLOORPLAN, *, wide: dict | None = None) -> Path:
    """The full-stack machine, or (`wide`: wide_rows' arguments) a wider one."""
    from ..gadget.floorplan import write
    if wide is None:
        lib = library(leaves)
        text = write(lib, title="A machine for FormalRV programs (surface code, d = 3)", comment=COMMENT)
    else:
        args = {"memories": 32, "benches": 4, "factories": 4, "rotations": 2, "per_row": 9, **wide}
        lib = library(leaves, rows=wide_rows(**args), name="fullstack_wide_d3")
        text = write(lib, title=f"A wide machine for FormalRV programs (surface code, d = 3, "
                                f"{args['memories']} memories)",
                     comment=WIDE_COMMENT.format(**args))
    Path(path).write_text(text, encoding="utf-8")
    return Path(path)
