"""The agent interface: what an agent may do on a page is what the code declares, nothing else.

THE RULE.  Anything a person can do on a QCCD page, an agent can find, read and do through a
declared interface; anything that is not declared, the agent cannot do -- its page tools refuse
it and say what is declared instead.  Every declaration lives in code and is read when the
page is served, so a rebuild changes what agents know with nothing to update by hand.
`tests/test_agent_interface.py` refuses a change that adds UI without its declaration.
(docs/agent-interface.md is the developer's version of this.)

Four kinds of thing are declared:

* PLACES -- where `navigate` may go: the site's own page index (generated by the site build,
  every page carries it) and the workspace's pages.  A link that is ON the page may be
  followed too: the page's author put it there.  A path that is neither is a guess, and is
  refused with the nearest real places.
* CONTROLS -- what `click`, `fill` and `press` may operate:
    - an element with `data-hint="<key>"` whose key the page describes (the Studio's explain
      layer, `EDITOR.hintFor`; a site page's own `window.QCCD_HINTS`) -- the inline way, and
      the only way for anything new;
    - a link, and a native fold-out (`<summary>`), which say what they do by being what they are;
    - a field or button inside a DECLARED FORM (a region the code generates from a schema,
      declared once as a whole);
    - an OUT-OF-LINE declaration in `OUT_OF_LINE` below, for controls on pages that cannot be
      edited right now without regenerating the whole site (the Studio's files are stamped
      into every page).  This list may only shrink: the test pins its length.
* VERBS -- the Studio's API (`window.EDITOR`), declared function by function in
  `qccd/viz/js/editor_api.json`; an agent's `studio` action calls only verbs declared for
  agents; on the person's own workspace Studio what a design verb draws is committed as the
  agent's change set (the page syncs it with `by_page_action`), and only the course's verbs,
  which would replace the design with a lesson's, stay off.
* ACTIONS and TOOLS -- the page actions (`service.PAGE_ACTIONS`, implemented in web/pageact.js)
  and the MCP tools (`mcp_server._tools`), declared by the code that serves them.

`manifest()` is all of it as one document: `qccd_read_reference(section='interface')`.
"""

