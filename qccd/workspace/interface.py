def api_keys(src: str) -> list:
    """The top-level keys of `var API = {...}` in editor.js (nested bodies and strings skipped)."""
    a = src.index("var API = {")
    i = a + len("var API = {")
    depth, keys = 1, []
    in_str, esc, line_comment, block_comment, at_key = None, False, False, False, True
    while depth > 0:
        c = src[i]
        nxt = src[i + 1] if i + 1 < len(src) else ""
        if line_comment:
            line_comment = c != "\n"
        elif block_comment:
            if c == "*" and nxt == "/":
                block_comment = False
                i += 1
        elif in_str:
            if esc:
                esc = False
            elif c == "\\":
                esc = True
            elif c == in_str:
                in_str = None
        elif c == "/" and nxt == "/":
            line_comment = True
        elif c == "/" and nxt == "*":
            block_comment = True
        elif c in "'\"`":
            in_str = c
        elif c in "{([":
            depth += 1
        elif c in "})]":
            depth -= 1
        elif depth == 1:
            if at_key:
                m = re.match(r"\s*([A-Za-z_$][\w$]*)\s*:", src[i:])
                if m:
                    keys.append(m.group(1))
                    i += m.end()
                    at_key = False
                    continue
            if c == ",":
                at_key = True
        i += 1
    return keys


def editor_api() -> dict:
    return json.loads(EDITOR_API.read_text(encoding="utf-8"))["verbs"]


def places(site_index: list | None) -> list:
    """Every place `navigate` may go on the website: the index's pages (their paths, each once)."""
    seen, out = set(), []
    for e in site_index or []:
        path = "/web/" + str(e.get("u") or "").split("#")[0].lstrip("/")
        if path not in seen:
            seen.add(path)
            out.append(path)
    return out


def page_contract(*, site_index: list | None = None, design_page: bool = False, aliases: list | None = None) -> dict:
    """What a page's tools enforce (web/pageact.js reads it as window.QCCD_INTERFACE)."""
    verbs = {k: {"kind": v["kind"], "does": v["does"], **({"args": v["args"]} if v.get("args") else {})}
             for k, v in editor_api().items() if v["use"] == "agent"}
    return {"verbs": verbs, "not_for_agents": {k: v["use"] for k, v in editor_api().items() if v["use"] != "agent"},
            "forms": DECLARED_FORMS, "controls": {k: v for k, v in OUT_OF_LINE.items()},
            "places": places(site_index) if site_index else None, "aliases": aliases or [],
            "design_page": design_page}


def manifest(ws=None, site_index: list | None = None) -> dict:
    """The whole interface as one document, generated from the code that implements it."""
    from .mcp_server import _tools
    from .service import PAGE_ACTIONS
    from .site_guide import studio_hints
    api = editor_api()
    return {
        "rule": ("You can do what is declared here and nothing else: a page action on an undeclared control, a "
                 "path that is no place, or an undeclared Studio verb is refused, and the refusal lists what is "
                 "declared instead. Read, scroll and highlight work on anything visible."),
        "places": {"workspace": WORKSPACE_PLACES,
                   "website": places(site_index) if site_index else "the site's index could not be read",
                   "also": "any link that is on the page you are on"},
        "controls": {"inline": [{"hint": h["hint"], "name": h["name"], "what": h["what"]} for h in studio_hints()],
                     "forms": DECLARED_FORMS,
                     "out_of_line": OUT_OF_LINE,
                     "by_construction": "links (they go where they point) and native fold-outs (<summary>)"},
        "studio_verbs": {k: v for k, v in api.items() if v["use"] == "agent"},
        "studio_verbs_not_for_agents": sorted(k for k, v in api.items() if v["use"] != "agent"),
        "page_actions": list(PAGE_ACTIONS),
        "tools": [{"name": n, "about": d} for n, d, _ in _tools()],
    }
