def catalogue_sections(repo: Path) -> tuple[list[str], dict[str, str]]:
    """The catalogue's own sections (its `# ---- name` comments), in order, and each rule's."""
    order: list[str] = []
    of: dict[str, str] = {}
    section = "Rules"
    text = (repo / "qccd/ruleset/library/catalogue.rules").read_text(encoding="utf-8")
    for line in text.splitlines():
        m = re.match(r"#\s*-{8,}\s*(.+?)\s*$", line)
        if m:
            section = m.group(1)[0].upper() + m.group(1)[1:]
            continue
        m = re.match(r"rule\s+(\S+)\s", line)
        if m:
            if section not in order:
                order.append(section)
            of[m.group(1)] = section
    return order, of


def website_groups(repo: Path) -> dict[str, str]:
    """The Rules page's categories (PR #24, `qccd/workspace/web/rules.js`), when it has them."""
    p = repo / "qccd/workspace/web/rules.js"
    out: dict[str, str] = {}
    if not p.is_file():
        return out
    text = p.read_text(encoding="utf-8")
    for m in re.finditer(r"\{\s*id:\s*'([^']+)',\s*title:\s*'([^']+)'.*?rules:\s*\[([^\]]*)\]", text, re.S):
        for rid in re.findall(r"'([^']+)'", m.group(3)):
            out[rid] = m.group(2)
    return out


def _review_module():
    """The review script beside this one: its `rule_reach` is what a device review uses, so the
    references say what the review does."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("qccd_design_review_review_for_sync",
                                                  Path(__file__).with_name("review.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def words_of(rule, terms) -> set[str]:
    """The vocabulary words a rule uses (its formula and its `when`)."""
    from qccd.ruleset.syntax import Call, Name, walk
    out = set()
    for f in (rule.formula, rule.when):
        for n in (walk(f) if f is not None else ()):
            w = n.fn if isinstance(n, Call) else n.id if isinstance(n, Name) else None
            if w in terms:
                out.add(w)
    return out


def goal3_families(repo: Path) -> dict[str, str]:
    """goals/goal3/families.py RULES: the rule set each Goal 3 family declares, when there is one."""
    p = repo / "goals" / "goal3" / "families.py"
    if not p.is_file():
        return {}
    m = re.search(r"^RULES\s*=\s*(\{.*?\})", p.read_text(encoding="utf-8"), re.S | re.M)
    if not m:
        return {}
    import ast
    try:
        return {str(k): str(v) for k, v in ast.literal_eval(re.sub(r"#[^\n]*", "", m.group(1))).items()}
    except (ValueError, SyntaxError):
        return {}


def source_lines(path: Path) -> dict[str, list[str]]:
    """A rule set file's include / use / drop / param lines, as written."""
    out: dict[str, list[str]] = defaultdict(list)
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"(include|use|drop|param)\s+(.+?)\s*$", line)
        if m:
            out[m.group(1)].append(m.group(2))
    return out


def probe_coverage() -> dict:
    """What the grader's rules stage reports, read off the code by running it.

    `qccd.verify.verify` is what the rules stage runs for every board; the rule language runs as
    well when the board's release names a rule set (the C2LR boards).  Running both on an empty
    programme, on one ordinary device and one C2LR device, says which rule ids each reports at
    all, which the verifier always skips or reports as partial, and which rules of the language
    need the input circuit (the rules stage passes none: they do not apply there)."""
    from qccd.api import Machine
    from qccd.cost.models import corrected_model
    from qccd.ir.tsir import TSIR
    from qccd.ruleset import NOT_APPLICABLE, check, load
    from qccd.ruleset.programme import programme_execution
    from qccd.verify import verify

    model = corrected_model("quantinuum")
    out = {}
    for kind, gen, params, rset in (("surface", "grid", {"a": 3, "b": 3}, "standard"),
                                    ("c2lr", "c2lr_grid", {"a": 2, "b": 2, "species": "Ba-Sr"}, "c2lr")):
        arch = getattr(Machine, gen)(**params, name=f"probe-{kind}").arch
        prog = TSIR(name="probe", arch_spec=arch.name, instructions=[])
        s = verify(prog, arch, model, check_metrics=False).rules.summary()
        lang = check(load(rset), programme_execution(prog, arch, model, check_metrics=False))
        # a reason can name the probe device's own numbers (C8's COM frequency): keep the words only
        def general(why: str) -> str:
            return re.sub(r"\s+at\s+[\d.]+\s*MHz", "", why)
        out[kind] = {
            "reported": sorted(set(s["passed"]) | set(s["failed"]) | set(s["skipped"]) | set(s["partial"])),
            "skipped": {k: general(v) for k, v in s["skipped"].items()},
            "partial": {k: general(v) for k, v in s["partial"].items()},
            "needs_circuit": sorted(r.id for r in lang.results
                                    if r.verdict == NOT_APPLICABLE and "circuit" in (r.reason or "")),
        }
    return out


def gather(repo: Path) -> dict:
    """Everything the references are written from, in one place."""
    _import(repo)
    from qccd.ruleset import LIBRARY, TERMS, catalogue, load, names, rule_order
    from qccd.ruleset import declared as dec
    from qccd.verify.rules import RULE_STATEMENTS
    from qccd.workspace import evaluator as ev
    from qccd.workspace.tasks import list_boards

    cat = catalogue()
    sections, section_of = catalogue_sections(repo)
    device_sets = {n: load(n) for n in names("device")}
    machine_sets = {n: load(n) for n in names("machine")}
    boards = list_boards()
    board_set = {b.id: (b.manifest.get("rules") or ev.BOARD_RULES) for b in boards}
    try:
        from qccd.site.rulespage import PARAM_NOTES
    except Exception:          # the site package is optional here
        PARAM_NOTES = {}
    try:
        from qccd.gadget import judge
        from qccd.gadget.place_checks import PLACE_RULES
        judge_doc = judge.__doc__ or ""
    except Exception:          # so is the gadget package
        PLACE_RULES, judge_doc = {}, ""
    reach = _review_module().rule_reach(cat)
    try:
        import qccd.evalset as evalset
        evaluations = {n: evalset.load(n) for n in evalset.names()}
    except Exception:          # an older checkout without the evaluation language
        evaluations = {}
    return {
        "repo": repo, "LIBRARY": LIBRARY, "TERMS": TERMS, "cat": cat, "rule_order": rule_order,
        "sections": sections, "section_of": section_of, "groups": website_groups(repo),
        "device_sets": device_sets, "machine_sets": machine_sets, "boards": boards, "board_set": board_set,
        "ev": ev, "dec": dec, "statements": RULE_STATEMENTS, "coverage": probe_coverage(),
        "param_notes": PARAM_NOTES, "reach": reach, "goal3": goal3_families(repo),
        "place_rules": dict(PLACE_RULES), "judge_doc": judge_doc, "evaluations": evaluations,
    }


def board_judgement(g: dict, rset: str, rid: str) -> str:
    """How the grader's rules stage judges rule `rid` on a board whose set is `rset`."""
    ev, cov = g["ev"], g["coverage"]["c2lr" if rset.startswith("c2lr") else "surface"]
    declared_by_release = rset != ev.BOARD_RULES
    if rid in cov["skipped"]:
        tol = "may be skipped" if rid in ev.ALLOWED_SKIPS else "BLOCKS if skipped"
        extra = "; decided by the certificate stages instead" if rid == "R10" else ""
        return f"{tol} (qccd.verify skips it: {cov['skipped'][rid]}){extra}"
    if rid in cov["partial"]:
        tol = "may be partial" if rid in ev.ALLOWED_PARTIAL else "BLOCKS if partial"
        return f"{tol} (qccd.verify: {cov['partial'][rid]})"
    if rid in cov["reported"]:
        return "must pass (qccd.verify" + (" and the rule language" if declared_by_release else "") + ")"
    if declared_by_release and rid not in cov["needs_circuit"]:
        return "must hold (the rule language only; qccd.verify does not report it)"
    if declared_by_release:
        return ("not judged by the rules stage: the rule language gets no circuit there, so it does not "
                "apply; only the certificate stages speak to it")
    return ("not judged by the rules stage: qccd.verify does not report it and the board's set is not "
            "run in the rule language; only the certificate stages speak to it")


