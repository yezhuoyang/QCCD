#!/usr/bin/env python3
"""Keep this skill's rule references in step with the code that defines the rules.

The rules a design is judged by live in the repository, not in this skill:

  qccd/ruleset/library/*.rules     every rule's text and every rule set (the website's Rules
                                   page prints exactly this text, `qccd/site/rulespage.py`)
  qccd/ruleset/vocabulary.py       the words a rule may use, and how each is read
  qccd/workspace/releases/         the boards: rule set, required checks, budget, limits
  qccd/workspace/evaluator.py      what the grader accepts (stages, allowed skips/partials, an
                                   entry's own rule set, conformance)
  qccd/verify/                     the verifier the grader's rules stage runs
  qccd/gadget/                     how a floorplan and a schedule are judged (the machine rules)
  goals/goal3/families.py          the rule set each Goal 3 family declares

Every file under `references/` except `review-guide.md` is GENERATED from those sources by
this script, so the skill never carries a hand-copied rule that could drift.

    python .claude/skills/qccd-design-review/scripts/sync_references.py            # check (default)
    python .claude/skills/qccd-design-review/scripts/sync_references.py --write    # regenerate
    python .claude/skills/qccd-design-review/scripts/sync_references.py --live     # check, and compare
                                                                                   # with qccd.academy/rules/

Exit codes: 0 current; 1 stale or missing (run --write); 2 the repository's code could not be
read; 3 (--live) the deployed Rules page differs from this checkout's rules.

Pure standard library, like the toolchain.  Output is deterministic (no dates, no commit ids),
so the files change exactly when a rule, a rule set, a board or the grader's policy does.
"""

