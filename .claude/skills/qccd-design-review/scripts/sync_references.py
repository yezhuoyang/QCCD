def _header(what: str) -> str:
    return (f"<!-- GENERATED by {SELF} from the repository's rule sources ({what}). Do not edit this file:\n"
            f"     change the sources and run `python {SELF} --write`. -->\n\n")


def repo_root(arg: str | None = None) -> Path:
    """The checkout whose rules this skill describes: --repo, else $QCCD_REPO, else the one the
    skill sits in (.claude/skills/<skill>/ -> the repository root)."""
    for cand in (arg, os.environ.get("QCCD_REPO"), str(SKILL.parents[2])):
        if cand and (Path(cand) / "qccd" / "ruleset" / "library" / "catalogue.rules").is_file():
            return Path(cand).resolve()
    raise SystemExit(2)


def _import(repo: Path):
    if str(repo) not in sys.path:
        sys.path.insert(0, str(repo))
    import qccd  # noqa: F401
    got = Path(sys.modules["qccd"].__file__).resolve().parents[1]
    if got != repo:
        raise ImportError(f"qccd was imported from {got}, not from {repo}")


def _md(s: str) -> str:
    """Text for a markdown table cell."""
    return " ".join(str(s).split()).replace("|", "\\|")


def _anchor(title: str) -> str:
    a = re.sub(r"[^\w\- ]", "", title.lower()).strip().replace(" ", "-")
    return re.sub(r"-+", "-", a)


