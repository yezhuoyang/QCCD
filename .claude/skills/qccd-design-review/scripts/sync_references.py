def gen_rules(g: dict) -> str:
    cat, sets, groups = g["cat"], g["device_sets"], g["groups"]
    in_sets: dict[str, list[str]] = defaultdict(list)
    for n, rs in sets.items():
        for rid in rs.ids:
            in_sets[rid].append(n)
    used_by: dict[str, list[str]] = defaultdict(list)
    for bid, rset in g["board_set"].items():
        used_by[rset].append(bid)
    board_sets = sorted(set(g["board_set"].values()))
    by_section: dict[str, list] = defaultdict(list)
    for r in cat.rules:
        by_section[g["section_of"].get(r.id, "Rules")].append(r)

    out = [_header("qccd/ruleset/library/catalogue.rules and the rule sets that use each rule"),
           "# Every device rule\n",
           f"The catalogue has {len(cat.rules)} rules. Each is printed exactly as the checker evaluates it, "
           "with the website's anchor, the rule sets that use it, and how the grader judges it on each kind "
           "of board. Words a rule uses are defined in `vocabulary.md`; rule sets in `rule-sets.md`.\n",
           "Board rule sets: " + "; ".join(f"`{s}` ({len(used_by[s])} boards)" for s in board_sets) + ".\n",
           "## Contents\n"]
    for sec in g["sections"]:
        ids = " ".join(r.id for r in by_section[sec])
        out.append(f"- [{sec}](#{_anchor(sec)}): {ids}")
    out.append("")
    for sec in g["sections"]:
        out.append(f"## {sec}\n")
        for r in by_section[sec]:
            core = " (core: holds in every rule set, cannot be dropped)" if r.core else ""
            out.append(f"### {r.id}: {r.title}\n")
            out.append(f"- Website: https://qccd.academy/rules/#{r.id}"
                       + (f" (category: {groups[r.id]})" if r.id in groups else "") + core)
            out.append(f"- In rule sets: {', '.join(sorted(in_sets[r.id])) or 'none shipped (catalogue only)'}")
            out.append(f"- Reads: {READS[g['reach'][r.id]]}")
            ws = words_of(r, g["TERMS"])
            only_sched = sorted(w for w in ws if "programme" not in g["TERMS"][w].kinds)
            only_prog = sorted(w for w in ws if "schedule" not in g["TERMS"][w].kinds)
            if only_sched:
                out.append(f"- Judged on: a paper's timed schedule only ({', '.join(f'`{w}`' for w in only_sched)} "
                           "exist only there), so it never applies to an entry's programme")
            elif only_prog:
                out.append(f"- Judged on: a programme only ({', '.join(f'`{w}`' for w in only_prog)} cannot be read "
                           "off a paper's schedule)")
            for s in board_sets:
                if r.id in sets[s].ids:
                    out.append(f"- On a `{s}` board: {board_judgement(g, s, r.id)}")
            own = [n for n in sorted(in_sets[r.id]) if n not in board_sets]
            if own:
                out.append(f"- In an entry's own set ({', '.join(own)}): must hold or not apply"
                           + ("; may go unchecked" if r.id in g["ev"].ALLOWED_SKIPS else "")
                           + " (`grader.md`, an entry's own rule set)")
            if r.source:
                out.append(f"- Sources: {r.source}")
            out.append(f"- Defined at: `qccd/ruleset/library/catalogue.rules:{r.line}`")
            if r.about:
                out.append(f"\n> {r.about}\n")
            body = ((f"when {r.when_text}:\n" if r.when is not None and r.when_text else "")
                    + (r.text or "").rstrip())
            out.append("```\n" + body + "\n```\n")
    return "\n".join(out).rstrip() + "\n"


def gen_rule_sets(g: dict) -> str:
    from qccd.ruleset import LIBRARY
    dec = g["dec"]
    used_by: dict[str, list[str]] = defaultdict(list)
    for b in g["boards"]:
        used_by[g["board_set"][b.id]].append(b.id)
    out = [_header("qccd/ruleset/library/*.rules"),
           "# Rule sets\n",
           "A rule set picks the catalogue rules a machine assumes (`use`), sets their parameters "
           "(`param`), may `include` another set, `drop` rules, or write its own. The rules marked core "
           f"(R0, R1, R8, R24) hold in every set. `python -m qccd.ruleset show <set>` prints any set resolved.\n",
           "## A leaderboard entry's own rule set (rules.json)\n",
           f"- A bundle may carry `rules.json` (kind `{dec.RULES_KIND}`, version 1): a shipped set by name, "
           "or a set written for the design. The grader judges the entry by it, and still checks the "
           "board's set: the report's `conformance` says which board rules the entry breaks, drops, "
           "replaces or adds.",
           f"- Read only by `qccd.ruleset.declared.load_declared`: at most {dec.MAX_TEXT // 1024} KB and "
           f"{dec.MAX_RULES} rules; level `device`; `include` may name only a shipped set; the core rules "
           "must be exactly the catalogue's.",
           "- Rankings list only entries that keep every board rule with the board's physics; `?rules=all` "
           "lists the others, tagged.\n",
           "## The shipped sets\n",
           "| Set | Rules | Boards that use it (see `boards.md`) | What it is |", "|---|---:|---|---|"]
    for n, rs in g["device_sets"].items():
        boards = used_by[n]
        cell = (f"{len(boards)}: " + ", ".join(f"`{b}`" for b in boards[:4]) + (", ..." if len(boards) > 4 else "")
                if boards else "-")
        out.append(f"| [`{n}`](#set-{n}) | {len(rs.rules)} | {cell} | {_md(rs.title)} |")
    out.append("")
    for n, rs in g["device_sets"].items():
        src = source_lines(LIBRARY / f"{n}.rules")
        out.append(f'<a id="set-{n}"></a>\n### `{n}`: {rs.title}\n')
        if rs.about:
            out.append(f"{rs.about}\n")
        for k in ("include", "drop"):
            if src.get(k):
                out.append(f"- {k}: " + "; ".join(f"`{x}`" for x in src[k]))
        out.append(f"- Rules ({len(rs.rules)}): " + " ".join(rs.ids))
        for k, v in rs.param_text.items():
            note = g["param_notes"].get(k)
            out.append(f"- param `{k} = {v}`" + (f": {note}" if note else ""))
        out.append(f"- Website: https://qccd.academy/rules/#set-{n}\n")
    return "\n".join(out).rstrip() + "\n"


def gen_boards(g: dict) -> str:
    out = [_header("qccd/workspace/releases/*/release.json and goals/goal3/families.py"),
           "# The boards\n",
           "Each board is one task release: its circuit, its physics (fixed blocks), the checks an entry "
           "must pass, its rule set and its ranking metric. The newest release of each task, in the "
           "website's order. A board is named by its title, its task, or `<task>@<release>`. A release "
           "that names no goal is Goal 1's.\n",
           "| # | Board | Release | Goal | Track | Rule set | Ranked by | Budget (DACs / junctions) | Limits (nodes / instructions) | Memory noise |",
           "|---:|---|---|---|---|---|---|---|---|---|"]
    for b in g["boards"]:
        m = b.manifest
        bud = b.physics().get("budget") or {}
        lim = m.get("limits") or {}
        out.append(f"| {m.get('order', '-')} | {_md(b.title)} | `{b.id}` | {m.get('goal', 'goal1')} | {m.get('track', '')} | "
                   f"`{g['board_set'][b.id]}` | `{m.get('rank_by')}` | {bud.get('max_dacs', '-')} / "
                   f"{bud.get('max_junctions', '-')} | {lim.get('max_nodes', '-')} / {lim.get('max_instructions', '-')} | "
                   f"{(m.get('qec') or {}).get('noise', '-')} |")
    if g["goal3"]:
        out.append("\n## Goal 3: each architecture family's own rule set\n")
        out.append("Goal 3 fixes the code and compares architectures. Every submission is judged by its own "
                   "rule set, the rules of the paper its machine comes from (`goals/goal3/families.py`, "
                   "`RULES`); the board's set decides only the board's own ranking (`grader.md`). An entry of a "
                   "family declares that set in its `rules.json`.\n")
        out.append("| Family | Rule set it declares |")
        out.append("|---|---|")
        for fam, rs in g["goal3"].items():
            out.append(f"| {fam} | [`{rs}`](rule-sets.md#set-{rs}) |")
    checks: dict[tuple, list[str]] = defaultdict(list)
    for b in g["boards"]:
        checks[tuple(b.required_checks)].append(b.id)
    out.append("\n## Required checks\n")
    out.append("Every required check must come back `passed` under the reference profile; skipped, "
               "unsupported, partial, timed out or cancelled is never eligible.\n")
    for cks, ids in sorted(checks.items(), key=lambda kv: (len(kv[0]), kv[0])):
        out.append(f"- {', '.join(f'`{c}`' for c in cks)}: {len(ids)} boards ({', '.join(f'`{i}`' for i in ids)})")
    trans = sorted({t for b in g["boards"] for t in (b.manifest.get("allowed_transformations") or [])})
    out.append(f"\nAllowed transformations between the certified and the final program: "
               f"{', '.join(f'`{t}`' for t in trans) or 'none'}.")
    fixed = sorted({k for b in g["boards"] for k in (b.manifest.get('physics') or {}).get('fixed_blocks', [])})
    out.append(f"Fixed physics blocks (the board's numbers win): {', '.join(f'`{k}`' for k in fixed)}.")
    return "\n".join(out).rstrip() + "\n"


def gen_grader(g: dict) -> str:
    ev, cov = g["ev"], g["coverage"]
    out = [_header("qccd/workspace/evaluator.py, qccd/verify, and a probe run of both verifiers"),
           "# What the grader accepts\n",
           "`qccd.workspace.evaluator.grade(release, bundle)` is the one grader: the official server, "
           "`qccd grade <bundle>` and `qccd submit --local` all call it.\n",
           "## Policy constants\n",
           f"- Stage statuses: {', '.join(f'`{s}`' for s in ev.STAGE_STATUSES)}",
           f"- The board's rule set when its release names none: `{ev.BOARD_RULES}`",
           f"- Rules the rules stage may report as skipped: {', '.join(sorted(ev.ALLOWED_SKIPS))}",
           f"- Rules the rules stage may report as partial: {', '.join(sorted(ev.ALLOWED_PARTIAL))}",
           "- Any other skipped or partial rule makes the rules stage `partial`, so the entry is not eligible.\n",
           "## How the rules stage judges each board rule\n",
           "Read off the code by running the stage's two checkers on an empty programme: `qccd.verify` "
           "(always) and the rule language (only when the board's release names a set). A rule the "
           "verifier does not report and the language does not reach is not judged by this stage.\n"]
    for rset in sorted(set(g["board_set"].values())):
        rs = g["device_sets"][rset]
        n = sum(1 for v in g["board_set"].values() if v == rset)
        out.append(f"### `{rset}` boards ({n})\n")
        out.append("| Rule | Title | Rules stage |")
        out.append("|---|---|---|")
        for r in rs.rules:
            out.append(f"| [{r.id}](https://qccd.academy/rules/#{r.id}) | {_md(r.title)} | "
                       f"{_md(board_judgement(g, rset, r.id))} |")
        out.append("")
    out.append("## An entry's own rule set\n")
    out.append("A bundle may declare its own set (`rules.json`; Goal 3's families do, `boards.md`). Then the "
               "rules stage's verdict is that set's, and the board's set decides only the board's own ranking. "
               "In the grader's words:\n")
    for fn in ("_rules_stage", "_declared_rules", "_conformance"):
        doc = " ".join((getattr(getattr(ev, fn, None), "__doc__", None) or "").split())
        if doc:
            out.append(f"- `evaluator.{fn}`: {doc}")
    out.append(f"- Rules of the entry's set that may go unchecked: {', '.join(sorted(ev.ALLOWED_SKIPS))}. Any other "
               "rule that could not be checked makes the stage `partial`, so the entry is not eligible.")
    out.append("- A rule of the entry's set that only a paper's timed schedule can judge (`rules.md`, \"Judged on\") "
               "does not apply to a programme: it neither fails nor counts.\n")
    evs = g["evaluations"]
    if any(e.requirements for e in evs.values()):
        out.append("## The evaluations' requirements (`qccd/evalset/library/*.eval`)\n")
        out.append("An evaluation's `require` lines are checks beside the rules: the device stage judges a board's "
                   "budget by `board`'s, and Goal 1 lists entries by `goal1`'s. Their ids are the evaluation's own: "
                   "Goal 1's G1-G3 are not the machine rules G1-G3 (`machine-rules.md`).\n")
        for n, e in evs.items():
            inherited = {r.id for i in (e.includes or []) if i in evs for r in evs[i].requirements}
            own = [r for r in e.requirements if r.id not in inherited]
            if not own:
                continue
            out.append(f"### `{n}`: {_md(e.title)}\n")
            if e.includes:
                out.append(f"- includes: {', '.join(f'`{i}`' for i in e.includes)}"
                           + (f" (its {', '.join(sorted(inherited))})" if inherited else ""))
            for k, v in (e.param_text or {}).items():
                if any(re.search(rf"\b{re.escape(k)}\b", r.text or "") for r in own):
                    out.append(f"- param `{k} = {v}`")
            out.append("")
            out.append("| Requirement | Title | Assertion | Meaning |")
            out.append("|---|---|---|---|")
            for r in own:
                out.append(f"| {r.id} | {_md(r.title)} | `{_md(r.text)}` | {_md(r.about)} |")
            out.append("")
    out.append("## What the probe found\n")
    for kind, c in cov.items():
        out.append(f"- {kind} device: qccd.verify reports {len(c['reported'])} rule ids "
                   f"({' '.join(c['reported'])}); skips {', '.join(sorted(c['skipped'])) or 'none'}; "
                   f"partial {', '.join(sorted(c['partial'])) or 'none'}; rule-language rules that need the "
                   f"circuit: {', '.join(c['needs_circuit']) or 'none'}")
    out.append("\n## The stages, in the evaluator's own words\n")
    out.append("```\n" + (ev.__doc__ or "").strip() + "\n```\n")
    out.append("## The verifier's one-line statements (`qccd.verify.rules.RULE_STATEMENTS`)\n")
    out.append("These are the verifier's own summaries. Where one reads differently from the catalogue, "
               "the catalogue (`rules.md`) is the rule.\n")
    out.append("| Rule | Statement |")
    out.append("|---|---|")
    for rid in sorted(g["statements"], key=g["rule_order"]):
        out.append(f"| {rid} | {_md(g['statements'][rid])} |")
    return "\n".join(out).rstrip() + "\n"


def _vocab_rows(terms) -> list[str]:
    out = ["| Word | Is | Meaning | Read off a programme | Read off a timed schedule |", "|---|---|---|---|---|"]
    for t in sorted(terms, key=lambda t: t.name):
        prog = t.programme or ("" if "programme" in t.kinds else "n/a")
        sched = t.schedule or ("" if "schedule" in t.kinds else "n/a")
        out.append(f"| `{_md(t.signature)}` | {_md(t.returns)} | {_md(t.meaning)} | {_md(prog)} | {_md(sched)} |")
    return out


def gen_vocabulary(g: dict) -> str:
    device = [t for t in g["TERMS"].values() if "machine" not in t.kinds]
    groups = [("hardware", "The device"), ("execution", "The execution"), ("time", "Instants and the state"),
              ("circuit", "The input circuit"), ("model", "The clock")]
    out = [_header("qccd/ruleset/vocabulary.py"),
           "# The words a device rule may use\n",
           "A rule is an assertion over these words and nothing else. A word an execution does not have "
           "makes a rule `does not apply` (never `holds`).\n"]
    known = {k for k, _ in groups}
    for key, title in groups + [("other", "Other")]:
        ts = [t for t in device if (t.group == key if key != "other" else t.group not in known)]
        if ts:
            out.append(f"## {title}\n")
            out.extend(_vocab_rows(ts))
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def gen_machine(g: dict) -> str:
    out = [_header("qccd/ruleset/library/floorplan.rules, machine.rules, qccd/ruleset/machine.py and qccd/gadget"),
           "# Machine-level rules: floorplans of places, and programs scheduled on them\n",
           "These judge a machine built from gadgets (`qccd/gadget`, docs/GADGETS.md), one level above a "
           "device. Use them when the design under review is a floorplan or a scheduled logical program, "
           "not a single device. Every op of a place is still a device programme judged by the device rules "
           "(`rules.md`), and H1 asks the roads between places to obey R1-R23 too.\n",
           "## How they are judged\n",
           "- `review.py --floorplan F.floor`: the floorplan rules (F1-F9) on the floorplan alone, as "
           "`python -m qccd.gadget floorplan F.floor` judges them.",
           "- `review.py --algorithm A.alg [--floorplan F.floor]`: the algorithm scheduled on the floorplan (the "
           "town unless it or `--floorplan` names one), then every machine rule (F, G and H), as `python -m "
           "qccd.gadget algorithm A.alg` judges them, beside the place checks and the schedule's sign-off.\n"]
    if g["judge_doc"]:
        out.append("In `qccd/gadget/judge.py`'s words:\n")
        out.append("```\n" + g["judge_doc"].strip() + "\n```\n")
    if g["place_rules"]:
        out.append("The place checks (`qccd/gadget/place_checks.py`, `PLACE_RULES`) are a second, Python checker of "
                   "these rules; where one reads differently from the rule text below, the rule text is the rule:\n")
        out.append("| Rule | Place check |")
        out.append("|---|---|")
        for rid, text in g["place_rules"].items():
            out.append(f"| {rid} | {_md(text)} |")
        out.append("")
    for n, rs in g["machine_sets"].items():
        out.append(f"## `{n}`: {rs.title}\n")
        if rs.about:
            out.append(f"{rs.about}\n")
        for r in rs.rules:
            core = " (core)" if r.core else ""
            out.append(f"### {r.id}: {r.title}{core}\n")
            out.append(f"- Website: https://qccd.academy/rules/#{r.id}")
            if r.source:
                out.append(f"- Sources: {r.source}")
            out.append(f"- Defined at: `qccd/ruleset/library/{n}.rules:{r.line}`")
            if r.about:
                out.append(f"\n> {r.about}\n")
            body = ((f"when {r.when_text}:\n" if r.when is not None and r.when_text else "") + (r.text or "").rstrip())
            out.append("```\n" + body + "\n```\n")
    words = [t for t in g["TERMS"].values() if "machine" in t.kinds]
    if words:
        out.append("## The words machine-level rules use\n")
        out.extend(_vocab_rows(words))
    return "\n".join(out).rstrip() + "\n"


def generate(repo: Path) -> dict[str, str]:
    g = gather(repo)
    files = {"rules.md": gen_rules(g), "rule-sets.md": gen_rule_sets(g), "boards.md": gen_boards(g),
             "grader.md": gen_grader(g), "vocabulary.md": gen_vocabulary(g), "machine-rules.md": gen_machine(g)}
    manifest = {
        "kind": "qccd-design-review.references", "version": 1,
        "generator": SELF, "sources": list(SOURCES),
        "counts": {"device_rules": len(g["cat"].rules), "device_rule_sets": len(g["device_sets"]),
                   "machine_rules": sum(len(rs.rules) for rs in g["machine_sets"].values()),
                   "boards": len(g["boards"]), "words": len(g["TERMS"]),
                   "requirements": len({(r.id, r.text) for e in g["evaluations"].values() for r in e.requirements})},
        # the digest of each set as `RuleSet.text()` writes it: the same text the compiler is given
        "rule_sets": {n: "sha256:" + hashlib.sha256(rs.text().encode()).hexdigest()
                      for n, rs in {**g["device_sets"], **g["machine_sets"]}.items()},
        "boards": {b.id: b.digest for b in g["boards"]},
        "files": {k: "sha256:" + hashlib.sha256(v.encode()).hexdigest() for k, v in files.items()},
    }
    files["MANIFEST.json"] = json.dumps(manifest, indent=1, sort_keys=True) + "\n"
    return files


# --------------------------------------------------------------------------- the deployed page

def _fetch(url: str, timeout: float = 30.0) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "qccd-design-review/1"})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return resp.read().decode("utf-8", errors="replace")


def _plain(s: str | None) -> str:
    return " ".join(html.unescape(re.sub(r"<[^>]+>", "", s or "")).split())


def live_sets(page: str) -> dict[str, dict]:
    """Every rule set on the deployed Rules page: name -> {rules, params}. A device set is a row of
    the sets table (its rules as chips, its parameters as `name = value`); a machine set is a
    heading followed by its rule cards."""
    out = {}
    for m in re.finditer(r'<tr id="set-([^"]+)">(.*?)</tr>', page, re.S):
        chips = re.search(r'<div class="chips">(.*?)</div>', m.group(2), re.S)
        params = {}
        for c in re.findall(r"<code>(.*?)</code>", m.group(2), re.S):
            k, sep, v = _plain(c).partition(" = ")
            if sep:
                params[k] = v
        out[m.group(1)] = {"rules": re.findall(r'<a href="#([^"]+)"', chips.group(1)) if chips else [],
                           "params": params}
    heads = list(re.finditer(r'<h3 id="set-([^"]+)">', page))
    for i, h in enumerate(heads):
        nxt = page.find("<h2", h.end())
        end = min([x.start() for x in heads[i + 1:]] + ([nxt] if nxt >= 0 else []) + [len(page)])
        out.setdefault(h.group(1), {"rules": re.findall(r'<section class="rule" id="([^"]+)">', page[h.end():end]),
                                    "params": {}})
    return out


def live_rules(url: str = SITE_RULES, timeout: float = 30.0, page: str | None = None) -> dict[str, dict]:
    """Every rule card on the deployed Rules page: id -> {title, about, text}."""
    page = _fetch(url, timeout) if page is None else page
    out = {}
    for m in re.finditer(r'<section class="rule" id="([^"]+)">(.*?)</section>', page, re.S):
        body = m.group(2)
        t = re.search(r'<span class="st">(.*?)</span>', body, re.S)
        a = re.search(r'<p class="checks">(.*?)</p>', body, re.S)
        f = re.search(r'<pre class="assert">(.*?)</pre>', body, re.S)
        out[m.group(1)] = {"title": _plain(t.group(1) if t else ""), "about": _plain(a.group(1) if a else ""),
                           "text": _plain(f.group(1) if f else "")}
    return out


def compare_live(repo: Path, url: str = SITE_RULES) -> list[str]:
    _import(repo)
    from qccd.ruleset import load, names
    sets = {n: load(n) for n in names("device") + names("machine")}
    local = {}
    for rs in sets.values():
        for r in rs.rules:
            local[r.id] = r
    from qccd.ruleset import catalogue
    for r in catalogue().rules:
        local[r.id] = r
    page = _fetch(url)
    site = live_rules(url, page=page)
    if not site:
        return [f"{url}: no rule cards found (the page's layout may have changed)"]
    diffs = []
    site_sets = live_sets(page)
    for n in sorted(set(site_sets) - set(sets)):
        diffs.append(f"rule set {n} is on the website but not in this checkout")
    for n in sorted(set(sets) - set(site_sets)):
        diffs.append(f"rule set {n} is in this checkout but not on the website (not deployed yet)")
    for n in sorted(set(sets) & set(site_sets)):
        mine, theirs = sets[n], site_sets[n]
        if sorted(mine.ids) != sorted(theirs["rules"]):
            more, less = sorted(set(theirs["rules"]) - set(mine.ids)), sorted(set(mine.ids) - set(theirs["rules"]))
            diffs.append(f"rule set {n}: the website's rules differ (website only: {', '.join(more) or '-'}; "
                         f"checkout only: {', '.join(less) or '-'})")
        for k, v in theirs["params"].items():
            if k in mine.param_text and " ".join(str(mine.param_text[k]).split()) != v:
                diffs.append(f"rule set {n}: parameter {k} is {v} on the website, {mine.param_text[k]} here")
    for rid in sorted(set(site) - set(local)):
        diffs.append(f"{rid} is on the website but not in this checkout: pull the branch the site is built from")
    for rid in sorted(set(local) - set(site)):
        diffs.append(f"{rid} is in this checkout but not on the website (not deployed yet)")
    for rid in sorted(set(site) & set(local)):
        r, s = local[rid], site[rid]
        mine = {"title": " ".join(r.title.split()), "about": " ".join((r.about or "").split()),
                "text": " ".join(((f"when {r.when_text}: " if r.when is not None and r.when_text else "")
                                  + (r.text or "")).split())}
        for k in ("title", "about", "text"):
            if s[k] and mine[k] and s[k] != mine[k]:
                diffs.append(f"{rid}: the website's {k} differs from this checkout's")
    return diffs


