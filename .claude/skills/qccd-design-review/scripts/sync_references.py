def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if a generated reference is stale (default)")
    mode.add_argument("--write", action="store_true", help="regenerate the references")
    ap.add_argument("--live", nargs="?", const=SITE_RULES, default=None,
                    help=f"also compare this checkout's rules with the deployed Rules page (default {SITE_RULES})")
    ap.add_argument("--repo", default=None, help="the QCCD checkout (default: the one this skill is in)")
    a = ap.parse_args(argv)
    try:
        repo = repo_root(a.repo)
        files = generate(repo)
    except SystemExit:
        print("sync_references: no QCCD checkout found (pass --repo, or set QCCD_REPO)", file=sys.stderr)
        return 2
    except Exception as exc:  # the repository's code is what is being read
        print(f"sync_references: could not read the rules from the repository: {type(exc).__name__}: {exc}",
              file=sys.stderr)
        return 2
    status = 0
    if a.write:
        REFS.mkdir(parents=True, exist_ok=True)
        changed = []
        for name, text in files.items():
            p = REFS / name
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                p.write_text(text, encoding="utf-8", newline="\n")
                changed.append(name)
        print("references regenerated: " + (", ".join(changed) if changed else "nothing changed"))
    else:
        stale = [n for n, t in files.items()
                 if not (REFS / n).is_file() or (REFS / n).read_text(encoding="utf-8") != t]
        if stale:
            print("the skill's references are stale: " + ", ".join(stale))
            print(f"the rules changed in the repository; regenerate them with:\n  python {SELF} --write")
            status = 1
        else:
            m = json.loads(files["MANIFEST.json"])["counts"]
            print(f"references current: {m['device_rules']} device rules, {m['device_rule_sets']} rule sets, "
                  f"{m['machine_rules']} machine rules, {m['boards']} boards")
    if a.live:
        try:
            diffs = compare_live(repo, a.live)
        except Exception as exc:
            print(f"could not read {a.live}: {type(exc).__name__}: {exc}", file=sys.stderr)
            return status or 3
        if diffs:
            print(f"{a.live} differs from this checkout:")
            for d in diffs:
                print("  " + d)
            status = status or 3
        else:
            print(f"{a.live} matches this checkout's rules")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
